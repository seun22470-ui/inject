/**
 * Analyze prompt and generate project files, then verify by running code
 */
export async function buildProjectFromPrompt({ prompt, targetDir, files = null, autoRun = true }) {
  const workspacePath = path.resolve(process.cwd(), targetDir);
  await fs.mkdir(workspacePath, { recursive: true });

  const generatedFiles = [];
  const errors = [];

  // 1. Determine files to write
  let filesToWrite = {};

  if (files && typeof files === 'object' && Object.keys(files).length > 0) {
    filesToWrite = files;
  } else {
    // Intelligent heuristic classification from prompt
    const lower = prompt.toLowerCase();
    if (lower.includes('python') || lower.includes('flask') || lower.includes('fastapi') || lower.includes('django')) {
      filesToWrite = PROJECT_TEMPLATES['python-api'].files;
    } else if (lower.includes('html') || lower.includes('website') || lower.includes('landing') || lower.includes('css')) {
      filesToWrite = PROJECT_TEMPLATES['static-web'].files;
    } else {
      // Default to Node API
      filesToWrite = PROJECT_TEMPLATES['node-api'].files;
    }
  }

  // 2. Write files into workspace
  for (const [relPath, content] of Object.entries(filesToWrite)) {
    const fullPath = path.join(workspacePath, relPath);
    await fs.mkdir(path.dirname(fullPath), { recursive: true });
    await fs.writeFile(fullPath, content, 'utf8');
    generatedFiles.push(relPath);
  }

  // 3. Auto-run and verification
  let executionResult = null;
  if (autoRun) {
    // Check if package.json exists -> test syntax
    if (filesToWrite['package.json'] && filesToWrite['server.js']) {
      const checkCmd = 'node --check server.js';
      const checkRes = await executeCommand(checkCmd, workspacePath);
      if (!checkRes.success) {
        errors.push({ stage: 'syntax_check', detail: checkRes.stderr || checkRes.stdout });
      }
      executionResult = checkRes;
    } else if (filesToWrite['main.py']) {
      const checkCmd = 'python -m py_compile main.py';
      const checkRes = await executeCommand(checkCmd, workspacePath);
      if (!checkRes.success) {
        errors.push({ stage: 'python_compile', detail: checkRes.stderr || checkRes.stdout });
      }
      executionResult = checkRes;
    }
  }

  return {
    success: errors.length === 0,
    workspacePath,
    generatedFiles,
    errors,
    executionResult
  };
}
